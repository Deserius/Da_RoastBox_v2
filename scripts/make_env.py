#!/usr/bin/env python3
"""Create backend/.env for local development.

Used by setup.sh / setup.bat. Never overwrites an existing .env unless --force
is given, never prints a secret, and is Windows-safe: no shell quoting, pure
pathlib, UTF-8 throughout.

Every key this script sets is removed from the copied .env.example first, so the
result contains exactly one definition per key and this block always wins. Keys
that come after the first "secret" section in the example are preserved.
"""
from __future__ import annotations

import pathlib
import secrets
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
ENV = ROOT / "backend" / ".env"
EXAMPLE = ROOT / "backend" / ".env.example"

# Injected with the generated JWT below; everything else is a literal.
JWT_PLACEHOLDER = "__GENERATED_JWT_SECRET__"

BLOCK = [
    "",
    "# --- local development (generated by setup script) ---",
    "MONGO_URL=mongodb://localhost:27017",
    "DB_NAME=roastbox",
    f"JWT_SECRET={JWT_PLACEHOLDER}",
    "APP_ENV=development",
    "STORAGE_BACKEND=local",
    "AI_DEFAULT_PROVIDER=openai",
    "",
    "ENABLE_PREVIEW_LOGIN=true",
    "PREVIEW_UNLIMITED_CREDITS=true",
    "ALLOW_PREVIEW_HOSTED_AI=true",
    "PREVIEW_HOSTED_DAILY_SHOW_LIMIT=-1",
    "PREVIEW_HOSTED_DAILY_VOICE_LIMIT=-1",
    "ALLOW_DEV_LOGIN=true",
    "",
    "ALLOW_RUNTIME_SETTINGS=true",
    "RUNTIME_SETTINGS_PASSPHRASE=roastbox",
    "",
    "ROASTBOX_DRY_RUN=true",
    "",
]

MANAGED = {
    "MONGO_URL",
    "MONGODB_URL",  # older alias; MONGO_URL stays authoritative
    "DB_NAME",
    "JWT_SECRET",
    "APP_ENV",
    "STORAGE_BACKEND",
    "AI_DEFAULT_PROVIDER",
    "EMERGENT_LLM_KEY",
    "ENABLE_PREVIEW_LOGIN",
    "PREVIEW_UNLIMITED_CREDITS",
    "ALLOW_PREVIEW_HOSTED_AI",
    "PREVIEW_HOSTED_DAILY_SHOW_LIMIT",
    "PREVIEW_HOSTED_DAILY_VOICE_LIMIT",
    "ALLOW_DEV_LOGIN",
    "ALLOW_RUNTIME_SETTINGS",
    "RUNTIME_SETTINGS_PASSPHRASE",
    "ROASTBOX_DRY_RUN",
}


def _key_of(line: str) -> str | None:
    stripped = line.strip()
    if not stripped or stripped.startswith("#") or "=" not in stripped:
        return None
    return stripped.split("=", 1)[0].strip()


def main() -> int:
    if ENV.exists() and "--force" not in sys.argv:
        print(f"   {ENV.relative_to(ROOT)} already exists - leaving it alone")
        return 0
    if not EXAMPLE.exists():
        print(f"ERROR: {EXAMPLE} is missing; cannot generate .env", file=sys.stderr)
        return 1

    kept = [
        line
        for line in EXAMPLE.read_text(encoding="utf-8").splitlines()
        if _key_of(line) not in MANAGED
    ]

    jwt = secrets.token_hex(32)
    body = kept + [ln.replace(JWT_PLACEHOLDER, jwt) for ln in BLOCK]
    ENV.write_text("\n".join(body) + "\n", encoding="utf-8")

    print(f"   wrote {ENV.relative_to(ROOT)} (gitignored)")
    print(f"   JWT_SECRET generated: {len(jwt)} hex chars")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
