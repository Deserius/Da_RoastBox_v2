#!/usr/bin/env python3
"""Start Da RoastBox's backend, diagnose what is wrong, and open the browser.

Why this exists
---------------
``uvicorn server:app`` fails with a bare traceback for every avoidable
misconfiguration: a missing module, a missing ``backend/.env``, no database, a
port already in use. This launcher checks each of those first, fixes what it
safely can, and prints a short instruction for anything it cannot.

It also starts the frontend dev server when one is needed, waits for both to
answer, and opens the default browser.

Usage
-----
    python run_server.py               # backend only, open http://localhost:3000
    python run_server.py --backend-only
    python run_server.py --port 8001 --no-browser
    python run_server.py --fix         # repair .env/dependencies, then start
    python run_server.py --check       # diagnose only, change nothing

Run it with the project venv:
    ..\\.venv\\Scripts\\python run_server.py      (from backend\\)
"""
from __future__ import annotations

import argparse
import importlib.util
import os
import shutil
import socket
import subprocess
import sys
import threading
import time
import urllib.error
import urllib.request
import webbrowser
from pathlib import Path

BACKEND = Path(__file__).resolve().parent
ROOT = BACKEND.parent
ENV_FILE = BACKEND / ".env"
ENV_EXAMPLE = BACKEND / ".env.example"

# Modules that must import before uvicorn can load server:app. Checked up front
# so the user gets a package name instead of a 40-line traceback.
REQUIRED = [
    ("fastapi", "fastapi"),
    ("uvicorn", "uvicorn"),
    ("pydantic", "pydantic"),
    ("pymongo", "pymongo"),
    ("motor", "motor"),
    ("openai", "openai"),
    ("stripe", "stripe"),
    ("elevenlabs", "elevenlabs"),
    ("dotenv", "python-dotenv"),
    ("multipart", "python-multipart"),
    ("cryptography", "cryptography"),
]

OK = "  [ok]   "
WARN = "  [warn] "
FAIL = "  [fail] "
INFO = "  ...    "


def say(marker: str, text: str) -> None:
    print(marker + text, flush=True)


def rule(title: str = "") -> None:
    print("\n" + ("=" * 62), flush=True)
    if title:
        print("  " + title, flush=True)
        print("=" * 62, flush=True)


# --------------------------------------------------------------------- checks
def check_python() -> list[str]:
    problems = []
    major, minor = sys.version_info[:2]
    if (major, minor) < (3, 11):
        problems.append(
            f"Python {major}.{minor} is too old. Install 3.11 or newer "
            "(3.13 or 3.14 recommended) and recreate .venv."
        )
    else:
        say(OK, f"Python {major}.{minor}.{sys.version_info[2]}")
    return problems


def check_modules() -> list[str]:
    missing = []
    for module, package in REQUIRED:
        if importlib.util.find_spec(module) is None:
            missing.append(package)
    if missing:
        say(FAIL, "Missing Python packages: " + ", ".join(sorted(set(missing))))
        problems = [
            "Install the backend dependencies, then run this again:",
            "    ..\\.venv\\Scripts\\python -m pip install -r requirements.txt"
            if os.name == "nt" else
            "    ../.venv/bin/python -m pip install -r requirements.txt",
        ]
        return problems
    say(OK, f"All {len(REQUIRED)} required packages import")
    return []


def check_env(fix: bool) -> list[str]:
    if ENV_FILE.exists():
        say(OK, f"{rel(ENV_FILE)} found")
        return []
    if not fix:
        say(FAIL, f"{rel(ENV_FILE)} is missing")
        return [
            "Create it, then run this again:",
            "    python run_server.py --fix      (generates a working .env)",
        ]
    say(WARN, f"{rel(ENV_FILE)} missing - generating one from .env.example")
    generator = ROOT / "scripts" / "make_env.py"
    if generator.exists():
        rc = subprocess.call([sys.executable, str(generator)])
        if rc == 0 and ENV_FILE.exists():
            say(OK, f"{rel(ENV_FILE)} generated")
            return []
    # Fallback if the helper is absent: copy the example and add a secret.
    import secrets

    text = ENV_EXAMPLE.read_text(encoding="utf-8") if ENV_EXAMPLE.exists() else ""
    lines = [ln for ln in text.splitlines()
             if not ln.strip().startswith(("MONGO_URL=", "DB_NAME=", "JWT_SECRET="))]
    lines += [
        "", "# --- generated by run_server.py ---",
        "MONGO_URL=mongodb://localhost:27017",
        "DB_NAME=roastbox",
        f"JWT_SECRET={secrets.token_hex(32)}",
    ]
    ENV_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")
    say(OK, f"{rel(ENV_FILE)} generated")
    return []


def check_env_values() -> list[str]:
    """Read .env without importing the app, and flag values that break startup."""
    problems = []
    values: dict[str, str] = {}
    for line in ENV_FILE.read_text(encoding="utf-8", errors="replace").splitlines():
        s = line.strip()
        if not s or s.startswith("#") or "=" not in s:
            continue
        key, _, val = s.partition("=")
        values[key.strip()] = val.strip()

    jwt = values.get("JWT_SECRET", "")
    if not jwt:
        problems.append("JWT_SECRET is empty in backend/.env - sign-in will fail. "
                        "Run with --fix to regenerate, or set any long random string.")
    elif len(jwt) < 32:
        say(WARN, f"JWT_SECRET is only {len(jwt)} characters; use 32 or more.")
    else:
        say(OK, "JWT_SECRET present")

    mongo = values.get("MONGO_URL") or values.get("MONGODB_URL") or ""
    if not mongo:
        problems.append("MONGO_URL is not set in backend/.env.")
    elif mongo.startswith(("mongodb://localhost", "mongodb://127.0.0.1")):
        say(INFO, f"MONGO_URL points at a local database ({mongo})")
    else:
        say(INFO, "MONGO_URL points at a remote database")
    return problems


def check_port(port: int) -> list[str]:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.settimeout(0.4)
        if s.connect_ex(("127.0.0.1", port)) == 0:
            say(WARN, f"Port {port} is already in use")
            return [
                f"Something is already listening on port {port}.",
                f"Stop it, or start on another port:  python run_server.py --port {port + 1}",
                f"    Find it:  netstat -ano | findstr :{port}",
            ]
    say(OK, f"Port {port} is free")
    return []


def mongo_reachable() -> bool:
    host, port = "127.0.0.1", 27017
    try:
        with socket.create_connection((host, port), timeout=1.5):
            return True
    except OSError:
        return False


def check_database() -> list[str]:
    if mongo_reachable():
        say(OK, "MongoDB is reachable on 127.0.0.1:27017")
        return []
    say(WARN, "Nothing is listening on 127.0.0.1:27017")
    return [
        "No local MongoDB. The app will start, but database calls will fail.",
        "",
        "  Atlas (easiest, free, works on Windows 10 Home):",
        "    1. https://www.mongodb.com/cloud/atlas/register",
        "    2. Create a free M0 cluster, add a user + password",
        "    3. Network Access -> Allow Access From Anywhere",
        "    4. Connect -> Drivers -> copy the mongodb+srv:// string",
        "    5. Put it in backend\\.env as MONGO_URL=<string>",
        "",
        "  Local MongoDB 7.0.x for Windows x64 (unsupported on Win10 but works):",
        "    https://www.mongodb.com/try/download/community",
        "",
        "  Docker:  docker run -d -p 27017:27017 --name roastbox-mongo mongo:7",
    ]


def local_mongo_url() -> bool:
    """True when backend/.env points MONGO_URL at a local database."""
    try:
        text = ENV_FILE.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return False
    for line in text.splitlines():
        s = line.strip()
        if s.startswith(("MONGO_URL=", "MONGODB_URL=")):
            value = s.split("=", 1)[1].strip()
            return "localhost" in value or "127.0.0.1" in value
    return False


def rel(path: Path) -> str:
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


# -------------------------------------------------------------------- runtime
def wait_for(url: str, timeout: float) -> bool:
    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            with urllib.request.urlopen(url, timeout=1.5) as r:
                if r.status < 500:
                    return True
        except (urllib.error.URLError, OSError):
            pass
        time.sleep(0.4)
    return False


def frontend_ready() -> bool:
    for port in (3000, 3001):
        try:
            with urllib.request.urlopen(f"http://127.0.0.1:{port}", timeout=1.0):
                return True
        except (urllib.error.URLError, OSError):
            continue
    return False


def start_frontend() -> subprocess.Popen | None:
    frontend = ROOT / "frontend"
    if not (frontend / "package.json").exists():
        return None
    if not (frontend / "node_modules").exists():
        say(WARN, "frontend/node_modules is missing - skipping the frontend")
        say(INFO, "Install it once:  cd frontend && yarn install --ignore-engines")
        return None
    yarn = shutil.which("yarn")
    if not yarn:
        say(WARN, "yarn is not on PATH - skipping the frontend")
        return None

    env = dict(os.environ)
    env.setdefault("BROWSER", "none")      # we open the browser ourselves
    env.setdefault("PORT", "3000")
    env.setdefault("HOST", "0.0.0.0")
    creation = subprocess.CREATE_NEW_PROCESS_GROUP if os.name == "nt" else 0
    try:
        proc = subprocess.Popen(
            [yarn, "start"], cwd=str(frontend), env=env,
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
            text=True, bufsize=1, creationflags=creation,
        )
    except OSError as exc:
        say(FAIL, f"Could not start the frontend: {exc}")
        return None
    say(INFO, "Frontend starting (first compile takes a minute)")

    def pump() -> None:
        assert proc.stdout is not None
        for line in proc.stdout:
            if any(k in line for k in ("Compiled", "Failed to compile", "error", "Error")):
                print("  frontend | " + line.rstrip(), flush=True)

    threading.Thread(target=pump, daemon=True).start()
    return proc


def open_browser_when_ready(url: str, backend_health: str, timeout: float) -> None:
    deadline = time.time() + timeout
    while time.time() < deadline:
        if wait_for(backend_health, 2):
            break
        time.sleep(0.5)
    # Give the dev server a moment to finish its first compile.
    for _ in range(int(timeout)):
        if frontend_ready():
            break
        time.sleep(1)
    try:
        webbrowser.open(url)
        say(OK, f"Opened {url} in your default browser")
    except Exception as exc:  # noqa: BLE001 - browser choice is best effort
        say(WARN, f"Could not open a browser automatically ({exc})")
        say(INFO, f"Open it yourself: {url}")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Start Da RoastBox and open the browser.")
    ap.add_argument("--port", type=int, default=int(os.environ.get("PORT", "8001")))
    ap.add_argument("--host", default=os.environ.get("HOST", "127.0.0.1"))
    ap.add_argument("--no-browser", action="store_true")
    ap.add_argument("--backend-only", action="store_true")
    ap.add_argument("--fix", action="store_true", help="repair .env before starting")
    ap.add_argument("--check", action="store_true", help="diagnose only, then exit")
    ap.add_argument("--reload", action="store_true", help="auto-reload on file changes")
    args = ap.parse_args(argv)

    os.chdir(BACKEND)
    if str(BACKEND) not in sys.path:
        sys.path.insert(0, str(BACKEND))

    rule("Da RoastBox - startup checks")
    problems: list[str] = []
    problems += check_python()
    problems += check_modules()
    if not problems:
        problems += check_env(args.fix)
    if ENV_FILE.exists():
        problems += check_env_values()
    problems += check_port(args.port)
    db_notes = check_database()

    blocking = [p for p in problems if p]
    if blocking:
        rule("Fix these before the server can start")
        for line in blocking:
            print("  " + line if line else "", flush=True)
        print(flush=True)
        return 1

    if db_notes:
        rule("Database")
        for line in db_notes:
            print("  " + line if line else "", flush=True)
        # A local MONGO_URL that refuses connections makes uvicorn's own startup
        # fail 30 seconds later with a pymongo traceback. Stop here instead.
        if local_mongo_url() and not mongo_reachable():
            print(flush=True)
            print("  Refusing to start: MONGO_URL points at localhost but nothing", flush=True)
            print("  is listening. Finish one of the options above, then re-run.", flush=True)
            print(flush=True)
            return 1

    if args.check:
        rule("All checks passed")
        return 0

    # Import the app here so an import error is reported cleanly.
    try:
        import server  # noqa: F401  - imported for its side effects
    except ModuleNotFoundError as exc:
        rule("Import failed")
        print(f"  Missing module: {exc.name}", flush=True)
        print(
            "  The package it belongs to is not installed. Reinstall:\n"
            "      ..\\.venv\\Scripts\\python -m pip install -r requirements.txt"
            if os.name == "nt" else
            "  The package it belongs to is not installed. Reinstall:\n"
            "      ../.venv/bin/python -m pip install -r requirements.txt",
            flush=True,
        )
        return 1
    except Exception as exc:  # noqa: BLE001 - configuration errors land here
        rule("Startup failed")
        print(f"  {type(exc).__name__}: {exc}", flush=True)
        print("  This is usually a bad value in backend/.env.", flush=True)
        return 1

    frontend_url = "http://localhost:3000"
    frontend_proc = None
    if not args.backend_only and not frontend_ready():
        frontend_proc = start_frontend()
    elif frontend_ready():
        say(OK, "A frontend is already running")

    if not args.no_browser:
        threading.Thread(
            target=open_browser_when_ready,
            args=(frontend_url, f"http://127.0.0.1:{args.port}/api/health", 120),
            daemon=True,
        ).start()

    rule(f"Starting API on http://{args.host}:{args.port}")
    print("  Settings console passphrase: roastbox", flush=True)
    print("  Press Ctrl-C to stop.\n", flush=True)

    import uvicorn

    try:
        uvicorn.run(
            "server:app", host=args.host, port=args.port,
            reload=args.reload, log_level="info",
        )
    except KeyboardInterrupt:
        say(INFO, "Stopped")
    finally:
        if frontend_proc and frontend_proc.poll() is None:
            say(INFO, "Stopping the frontend")
            frontend_proc.terminate()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
